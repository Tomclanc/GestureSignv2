using System.Drawing;
using GestureSign.Daemon.Triggers;
using GestureSign.Daemon.Input;
using GestureSign.Common.Input;
using GestureSign.Common.Applications;
using GestureSign.CorePlugins.MouseActions;
using ManagedWinapi.Hooks;
int checks = 0;
void Check(bool value, string name) { if (!value) throw new Exception(name); checks++; }
var trigger = new DesktopEdgeWheelTrigger(); int fired = 0;
trigger.TriggerFired += (_, e) => { Check(e.SourceDevice == Devices.Mouse, "explicit mouse source"); fired++; };
bool Wheel(int x, int y, int delta = 120, int flags = 0, int message = 0x20A, bool handled = false)
    => PointCapture.Instance.MouseHook.Send(new() { Point = new Point(x,y), MouseData = delta, Flags = flags, Message = message }, handled);
System.Windows.Forms.Screen.AllScreens = [new(new Rectangle(0,0,100,100))];
Check(Wheel(0,50) && ApplicationManager.Instance.Last == "DesktopEdge.Left.WheelUp", "left up");
Check(Wheel(99,50,-120) && ApplicationManager.Instance.Last == "DesktopEdge.Right.WheelDown", "right down");
Check(Wheel(50,0) && ApplicationManager.Instance.Last == "DesktopEdge.Top.WheelUp", "top up");
Check(Wheel(50,99) && ApplicationManager.Instance.Last == "DesktopEdge.Bottom.WheelUp", "bottom up");
var count = fired;
Check(!Wheel(50,50), "interior ignored"); Check(!Wheel(0,50,flags:1), "injected ignored");
Check(!Wheel(0,50,0), "zero delta ignored"); Check(!Wheel(0,50,message:0x20E), "horizontal wheel ignored");
PointCapture.Instance.Mode = CaptureMode.Training; Check(!Wheel(0,50), "training ignored");
PointCapture.Instance.Mode = CaptureMode.UserDisabled; Check(!Wheel(0,50), "paused ignored");
PointCapture.Instance.Mode = CaptureMode.Normal; PointCapture.Instance.State = CaptureState.Capturing;
Check(!Wheel(0,50), "active gesture ignored"); PointCapture.Instance.State = CaptureState.Ready;
ApplicationManager.Instance.Allow = false; Check(!Wheel(0,50), "unassigned/excluded preserves native scroll"); ApplicationManager.Instance.Allow = true;
System.Windows.Forms.Screen.AllScreens = [new(new Rectangle(0,0,100,100)), new(new Rectangle(100,0,100,100))];
Check(!Wheel(99,50), "internal monitor edge ignored");
Check(fired == count, "rejected events never dispatch");
Check(Wheel(199,50), "outer secondary monitor edge");
System.Windows.Forms.Screen.AllScreens = [new(new Rectangle(-100,0,100,100))];
Check(Wheel(-100,50), "negative monitor coordinates");
bool physical = false, escape = false;
DragLock.KeyIsDown = key => key == 1 ? physical : escape;
DragLock.Release(); Check(WindowsInput.InputSimulator.Up == 0, "idle release cannot release physical button");
physical = true; DragLock.Toggle(); Check(WindowsInput.InputSimulator.Down == 0, "physical ownership preserved");
physical = false; DragLock.Toggle(); Check(WindowsInput.InputSimulator.Down == 1, "toggle acquires once");
DragLock.Toggle(); Check(WindowsInput.InputSimulator.Up == 1, "toggle releases once");
DragLock.Release(); Check(WindowsInput.InputSimulator.Up == 1, "release is idempotent");
DragLock.Toggle(); escape = true;
Check(SpinWait.SpinUntil(() => WindowsInput.InputSimulator.Up == 2, 2000), "Esc releases through guard timer");
escape = false; DragLock.Toggle(); WindowsInput.InputSimulator.FailUp = true; DragLock.Release();
WindowsInput.InputSimulator.FailUp = false; DragLock.Release(); Check(WindowsInput.InputSimulator.Up == 3, "failed release retains ownership for retry");
Console.WriteLine($"PASS: {checks} desktop-edge dispatch and drag-lock lifecycle checks (simulated input; no real clicks).");
